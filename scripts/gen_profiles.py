"""Turns the Tescom UPS profiles into C++ tables for the firmware.

The profiles live in one place: profiles/*.conf on the main branch of the Tescom nut-app
repository (github.com/georgecm/nut-app), one NUT ups.conf section per model, the one
source for the app, the Raspberry Pi, the add-on and this firmware. Its
tools/export-profiles writes them as JSON; a copy is kept here in
profiles/tescom-profiles.json so the firmware builds offline.

The JSON is always refreshed from nut-app's main branch (origin/main, fetched first), never
from a checkout's working tree: a clone on an older branch would drop the models added on
main since.

    python scripts/gen_profiles.py            # refresh the JSON from nut-app main when a
                                              # clone is found, then write UpsProfiles.gen.h
    python scripts/gen_profiles.py --check    # exit 1 when either is out of date

A clone of nut-app is looked up in $TESCOM_NUT_APP, then next to this repository
(../nut-app, ../nut-app-release). Also runs as a PlatformIO pre: script.
"""

import json
import os
import subprocess
import sys
from pathlib import Path

try:
    ROOT = Path(__file__).resolve().parent.parent
except NameError:  # PlatformIO runs extra scripts with exec(), without __file__
    Import("env")  # noqa: F821
    ROOT = Path(env["PROJECT_DIR"])  # noqa: F821

JSON_PATH = ROOT / "profiles" / "tescom-profiles.json"
HEADER_PATH = ROOT / "lib" / "USBHostUPS" / "src" / "UpsProfiles.gen.h"


NUT_APP_REMOTE = "georgecm/nut-app"
MAIN = "origin/main"


def git(repo, *args, **kw):
    return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, timeout=60, **kw)


def nut_app_clones():
    candidates = []
    if os.environ.get("TESCOM_NUT_APP"):
        candidates.append(Path(os.environ["TESCOM_NUT_APP"]))
    candidates += [ROOT.parent / "nut-app", ROOT.parent / "nut-app-release"]
    for base in candidates:
        try:
            url = git(base, "remote", "get-url", "origin").stdout.decode().strip()
        except (OSError, subprocess.SubprocessError):
            continue
        if NUT_APP_REMOTE in url:
            yield base


def main_exporter(workdir):
    """tools/export-profiles and profiles/ as they are on nut-app main, in workdir."""
    for repo in nut_app_clones():
        # Best effort: offline, the last fetched main is used
        try:
            git(repo, "fetch", "--quiet", "origin", "main")
        except subprocess.SubprocessError:
            pass
        rev = git(repo, "rev-parse", "--short", MAIN)
        if rev.returncode != 0:
            continue
        archive = git(repo, "archive", MAIN, "profiles", "tools/export-profiles")
        if archive.returncode != 0:
            continue
        subprocess.run(["tar", "-x", "-C", str(workdir)], input=archive.stdout, check=True)
        print(f"gen_profiles: profiles from nut-app main ({rev.stdout.decode().strip()}, via {repo.name})")
        return workdir / "tools" / "export-profiles"
    return None


def refresh_json(check):
    import tempfile

    with tempfile.TemporaryDirectory() as tmp:
        tool = main_exporter(Path(tmp))
        if tool is None:
            print(f"gen_profiles: no nut-app clone found, using {JSON_PATH.relative_to(ROOT)} as it is")
            return True
        args = [sys.executable, str(tool)]
        args += ["--check", str(JSON_PATH)] if check else ["-o", str(JSON_PATH)]
        return subprocess.run(args).returncode == 0


def c_string(s):
    if s is None:
        return "nullptr"
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(data):
    out = [
        "// Generated by scripts/gen_profiles.py from profiles/tescom-profiles.json",
        "// (nut-app tools/export-profiles, from its main branch). Do not edit: change nut-app/profiles/*.conf on main.",
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "#pragma once",
        '#include "UpsProfiles.h"',
        "",
        "namespace UpsProfiles {",
        "namespace generated {",
        "",
    ]
    entries = []
    for p in data["profiles"]:
        ident = p["key"].replace("-", "_")
        options = [(k, "" if v is True else str(v)) for k, v in p["options"].items()]
        out.append(f"inline const Setting {ident}_options[] = {{")
        out += [f"    {{ {c_string(k)}, {c_string(v)} }}," for k, v in options] or ["    { nullptr, nullptr },"]
        out.append("};")
        out.append(f"inline const Setting {ident}_match[] = {{")
        out += [f"    {{ {c_string(k)}, {c_string(v)} }}," for k, v in p["match"]] or ["    { nullptr, nullptr },"]
        out.append("};")
        vid, pid = (int(x, 16) for x in p["usbId"].split(":")) if p["usbId"] else (0, 0)
        entries.append(
            f"    {{ {c_string(p['key'])}, {c_string(p['model'])}, {c_string(p['link'])}, "
            f"{'true' if p['usbId'] else 'false'}, 0x{vid:04x}, 0x{pid:04x}, "
            f"{c_string(p['driver'])}, {c_string(p['subdriver'])}, "
            f"{ident}_options, {len(options)}, {ident}_match, {len(p['match'])} }},"
        )
    out.append("")
    out.append(f"inline const char MANUFACTURER[] = {c_string(data.get('manufacturer', 'Tescom'))};")
    out.append("inline const Profile ALL[] = {")
    out += entries
    out.append("};")
    out.append(f"inline const size_t COUNT = {len(entries)};")
    out += ["", "} // namespace generated", "} // namespace UpsProfiles", ""]
    return "\n".join(out)


def main(check=False):
    ok = refresh_json(check)
    text = render(json.loads(JSON_PATH.read_text(encoding="utf-8")))
    current = HEADER_PATH.read_text(encoding="utf-8") if HEADER_PATH.exists() else ""
    if current != text:
        if check:
            print(f"gen_profiles: {HEADER_PATH.relative_to(ROOT)} is out of date", file=sys.stderr)
            ok = False
        else:
            HEADER_PATH.write_text(text, encoding="utf-8")
            print(f"gen_profiles: wrote {HEADER_PATH.relative_to(ROOT)}")
    return ok


if __name__ == "__main__":
    sys.exit(0 if main("--check" in sys.argv[1:]) else 1)
else:
    if not main():
        raise SystemExit("gen_profiles: export from nut-app failed")
